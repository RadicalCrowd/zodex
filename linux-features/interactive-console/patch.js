"use strict";

const MAIN_BUNDLE_PATTERN = /^main-[^.]+\.js$/;
const WEBVIEW_ASSET_PATTERN = /^app-initial-[^.]+\.js$/;
const CONSOLE_IPC_MARKER = "codex-linux-interactive-console-ipc";
const CONSOLE_RUNTIME_MARKER = "codex-linux-interactive-console-runtime";

function warn(message) {
  console.warn(`WARN: ${message} - skipping interactive-console patch`);
}

function consoleIpcRuntimeSource() {
  return [
    `/*${CONSOLE_IPC_MARKER}*/`,
    `;(()=>{`,
    `if(typeof require!=="undefined"&&typeof electron!=="undefined"||typeof require!=="undefined"){`,
    `try{`,
    `const {ipcMain}=require("electron");`,
    `const {PtyManager}=require("./features/interactive-console/pty-manager.js");`,
    `const manager=new PtyManager();`,
    `ipcMain.handle("zodex-console-sessions",()=>manager.listSessions());`,
    `ipcMain.handle("zodex-console-spawn",(e,opts)=>{`,
    `let s=manager.createSession(opts);`,
    `s.on("data",(chunk)=>{e.sender.send("zodex-console-data",{id:s.id,chunk});});`,
    `s.on("status",(st)=>{e.sender.send("zodex-console-status",{id:s.id,...st});});`,
    `s.on("waiting_for_input",(p)=>{e.sender.send("zodex-console-input-needed",{id:s.id,...p});});`,
    `return{id:s.id,status:s.status,command:s.command};`,
    `});`,
    `ipcMain.handle("zodex-console-input",(e,id,input,opts)=>manager.writeInput(id,input,opts));`,
    `ipcMain.handle("zodex-console-kill",(e,id,signal)=>manager.killSession(id,signal));`,
    `}catch(err){console.warn("WARN: zodex console ipc init failed",err);}`,
    `}`,
    `})();`,
  ].join("");
}

