function applyMainBundlePatch(source) {
  try {
    if (typeof source !== "string") return source;
    if (source.includes(CONSOLE_IPC_MARKER)) return source;
    return `${source}\n${consoleIpcRuntimeSource()}\n`;
  } catch (error) {
    warn(`Main bundle patch error: ${error.message}`);
    return source;
  }
}

function applyWebviewAssetPatch(source) {
  try {
    if (typeof source !== "string") return source;
    if (source.includes(CONSOLE_RUNTIME_MARKER)) return source;
    return `${source}\n${consoleWebviewRuntimeSource()}\n`;
  } catch (error) {
    warn(`Webview asset patch error: ${error.message}`);
    return source;
  }
}

